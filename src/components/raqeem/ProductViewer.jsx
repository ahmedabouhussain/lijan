import React from "react";
import { FileText, CheckCircle2, AlertCircle, Clock, Download, Printer, FileCheck } from "lucide-react";
import StatusBadge from "@/components/raqeem/StatusBadge";

const SECTION_ICONS = {
  opening: Clock,
  attendance: FileCheck,
  agenda_items: FileText,
  decisions: CheckCircle2,
  actions: FileText,
  closing: CheckCircle2,
  preamble: FileText,
  legal_basis: FileCheck,
  resolution_text: FileText,
  voting_results: CheckCircle2,
  execution_plan: FileText,
  dissent: AlertCircle,
  establishment: FileText,
  mandate: FileText,
  composition: FileText,
  governance_rules: FileText,
  meeting_procedures: Clock,
  voting_rules: CheckCircle2,
  term: Clock,
  executive_summary: FileText,
  achievements: CheckCircle2,
  challenges: AlertCircle,
  financial_overview: FileText,
  recommendations: FileText,
  next_steps: Clock,
  summary: FileText,
  completed_actions: CheckCircle2,
  in_progress: Clock,
  overdue: AlertCircle,
  blockers: AlertCircle,
  overview: FileText,
  key_decisions: CheckCircle2,
  critical_actions: AlertCircle,
  risks: AlertCircle,
  details: FileText,
  default: FileText,
};

const STATUS_BADGES = {
  draft: { label_ar: "مسودة", label_en: "Draft", class: "bg-secondary text-secondary-foreground" },
  generated: { label_ar: "مُولّد", label_en: "Generated", class: "bg-blue-50 text-blue-700" },
  in_review: { label_ar: "قيد المراجعة", label_en: "In Review", class: "bg-amber-50 text-amber-700" },
  approved: { label_ar: "معتمد", label_en: "Approved", class: "bg-emerald-50 text-emerald-700" },
  published: { label_ar: "منشور", label_en: "Published", class: "bg-green-100 text-green-700" },
  archived: { label_ar: "مؤرشف", label_en: "Archived", class: "bg-secondary text-muted-foreground" },
};

export default function ProductViewer({ product, lang = "ar" }) {
  let sections = [];
  try {
    sections = product.generated_content ? JSON.parse(product.generated_content) : [];
  } catch {}

  const statusBadge = STATUS_BADGES[product.status] || STATUS_BADGES.draft;

  return (
    <div className="space-y-4">
      {/* Product Header */}
      <div className="raqeem-card p-4">
        <div className="flex items-start justify-between gap-3">
          <div className="min-w-0">
            <h2 className="text-base font-bold text-foreground">{product.title_ar || product.title}</h2>
            {product.source_title && product.source_title !== product.title && (
              <p className="text-xs text-muted-foreground mt-0.5">{product.source_title}</p>
            )}
            <div className="flex items-center gap-2 mt-2 text-xs text-muted-foreground">
              <span>{lang === "ar" ? "نوع" : "Type"}: {product.product_type}</span>
              <span>·</span>
              <span>{lang === "ar" ? "الصيغة" : "Format"}: {product.export_format?.toUpperCase()}</span>
              <span>·</span>
              <span>{lang === "ar" ? "التصنيف" : "Classification"}: {product.classification}</span>
            </div>
            {product.generated_by_name && (
              <div className="text-xs text-muted-foreground mt-1">
                {lang === "ar" ? "أُنشئ بواسطة" : "Generated by"}: {product.generated_by_name}
                {product.generated_at && ` · ${new Date(product.generated_at).toLocaleDateString(lang === "ar" ? "ar-SA" : "en-US")}`}
              </div>
            )}
          </div>
          <StatusBadge
            label={lang === "ar" ? statusBadge.label_ar : statusBadge.label_en}
            colorClass={statusBadge.class}
          />
        </div>
        {product.ai_confidence > 0 && (
          <div className="flex items-center gap-2 mt-3 pt-3 border-t border-border">
            <span className="text-xs text-muted-foreground">{lang === "ar" ? "مستوى الثقة" : "AI Confidence"}:</span>
            <div className="flex-1 max-w-[120px] h-1.5 rounded-full bg-secondary overflow-hidden">
              <div
                className={`h-full rounded-full ${product.ai_confidence >= 0.7 ? "bg-emerald-500" : product.ai_confidence >= 0.4 ? "bg-amber-500" : "bg-destructive"}`}
                style={{ width: `${Math.round(product.ai_confidence * 100)}%` }}
              />
            </div>
            <span className="text-xs font-medium">{Math.round(product.ai_confidence * 100)}%</span>
            {product.human_edited && (
              <span className="text-xs text-emerald-600 flex items-center gap-1">
                <CheckCircle2 className="w-3 h-3" />
                {lang === "ar" ? "مُراجَع بشري" : "Human Reviewed"}
              </span>
            )}
          </div>
        )}
      </div>

      {/* Product Sections */}
      {sections.length > 0 ? (
        <div className="space-y-3">
          {sections.map((section, i) => {
            const Icon = SECTION_ICONS[section.section_key] || SECTION_ICONS.default;
            const sectionTitle = lang === "ar" ? section.title_ar : section.title_en || section.title_ar;
            const sectionContent = lang === "ar" ? section.content_ar : section.content_en || section.content_ar;
            return (
              <div key={i} className="raqeem-card p-4 space-y-2">
                <div className="flex items-center gap-2">
                  <div className="w-8 h-8 rounded-md bg-primary/8 flex items-center justify-center shrink-0">
                    <Icon className="w-4 h-4 text-primary" aria-hidden="true" />
                  </div>
                  <h4 className="text-sm font-semibold text-foreground">{sectionTitle}</h4>
                </div>
                {sectionContent ? (
                  <p className="text-sm text-foreground/80 leading-relaxed whitespace-pre-line">{sectionContent}</p>
                ) : (
                  <p className="text-sm text-muted-foreground italic">
                    {lang === "ar" ? "أدلة غير كافية" : "Insufficient Evidence"}
                  </p>
                )}
                {section.source_references && section.source_references.length > 0 && (
                  <div className="flex flex-wrap gap-1.5 pt-1">
                    {section.source_references.map((ref, j) => (
                      <span key={j} className="text-xs px-2 py-0.5 rounded bg-secondary text-muted-foreground">
                        {ref.record_type || "سجل"}
                      </span>
                    ))}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      ) : (
        <div className="raqeem-card p-6 text-center text-sm text-muted-foreground">
          {lang === "ar" ? "لا توجد أقسام في هذا المنتج." : "No sections in this product."}
        </div>
      )}

      {/* Export Actions */}
      <div className="flex items-center gap-2">
        <button
          onClick={() => window.print()}
          className="inline-flex items-center gap-2 px-3 py-2 rounded-md border border-input text-sm hover:bg-secondary/30"
        >
          <Printer className="w-4 h-4" />
          {lang === "ar" ? "طباعة" : "Print"}
        </button>
        {product.file_url && (
          <a
            href={product.file_url}
            target="_blank"
            rel="noreferrer"
            className="inline-flex items-center gap-2 px-3 py-2 rounded-md bg-primary text-primary-foreground text-sm hover:bg-primary/90"
          >
            <Download className="w-4 h-4" />
            {lang === "ar" ? "تحميل" : "Download"}
          </a>
        )}
      </div>
    </div>
  );
}