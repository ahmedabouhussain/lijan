// exportContent.js — the canonical content model every PDF/DOCX export shares.
// Each product type maps its raw data into ONE shape: { title, subtitle, meta[], sections[] }.
// The renderers never read product-specific fields — they read this shape only.

const loc = (lang, ar, en) => (lang === "ar" ? ar : en);

function legislativeDossier({ data, language }) {
  const file = data?.file || {};
  const isAr = language === "ar";
  const t = (ar, en) => (isAr ? ar : en);
  const meta = [
    { label: t("المرجع الرسمي", "Reference"), value: file.reference_number || "—" },
    { label: t("الجهة المحيلة", "Referring body"), value: isAr ? file.referring_body : (file.referring_body_en || file.referring_body) || "—" },
    { label: t("اللجنة المختصة", "Committee"), value: isAr ? (data.committee_name_ar || file.committee_name_ar || file.committee_name || "—") : (data.committee_name_en || file.committee_name_en || file.committee_name_ar || file.committee_name || "—") },
    { label: t("التصنيف", "Classification"), value: data?.classification_label || "—" },
    { label: t("المرحلة", "Stage"), value: data?.stage_label || "—" },
  ];
  const sections = [];
  if (data?.conclusions || file.report_conclusions) {
    sections.push({ heading: t("النتائج", "Conclusions"), body: data?.conclusions || file.report_conclusions });
  }
  if (data?.recommendations || file.report_recommendations) {
    sections.push({ heading: t("التوصيات", "Recommendations"), body: data?.recommendations || file.report_recommendations });
  }
  const table = file.comparison_table || data?.comparison_table;
  if (table && table.length) {
    sections.push({
      heading: t("جدول المقارنة", "Comparison Table"),
      table: {
        columns: [
          { key: "article_no", label: t("المادة", "Art.") },
          { key: "referred_text", label: t("النص المحال", "Referred") },
          { key: "final_wording", label: t("الصياغة النهائية", "Final Wording") },
        ],
        rows: table.map((r, i) => ({
          article_no: String(r.article_no || i + 1),
          referred_text: r.referred_text || "—",
          final_wording: r.final_wording || r.proposed_text || "—",
        })),
      },
    });
  }
  return {
    title: t("تقرير اللجنة التشريعي", "Legislative Committee Report"),
    subtitle: isAr ? file.subject_title_ar : (file.subject_title_en || file.subject_title_ar),
    meta, sections,
  };
}

function productDocument({ data, language }) {
  // The "living product" path (documentEngine): generated_content sections + product meta.
  const product = data?.product || {};
  const isAr = language === "ar";
  const t = (ar, en) => (isAr ? ar : en);
  let raw = [];
  try { raw = product.generated_content ? JSON.parse(product.generated_content) : (data?.sections || []); } catch { raw = data?.sections || []; }
  const sections = (raw || []).map((s) => ({
    heading: isAr ? (s.title_ar || s.title) : (s.title_en || s.title_ar || s.title),
    body: isAr ? (s.content_ar || s.content) : (s.content_en || s.content_ar || s.content),
  }));
  return {
    title: isAr ? (product.title_ar || product.title) : product.title,
    subtitle: [product.committee_name, product.product_type, product.classification].filter(Boolean).join(" · ") || "",
    meta: [
      { label: t("النوع", "Type"), value: product.product_type || "—" },
      { label: t("التصنيف", "Classification"), value: product.classification || "—" },
      { label: t("أنشأه", "Generated by"), value: product.generated_by_name || "—" },
    ],
    sections,
  };
}

function generic({ data, language }) {
  return {
    title: data?.title || "",
    subtitle: data?.subtitle || "",
    meta: data?.meta || [],
    sections: data?.sections || [],
  };
}

export function buildExportContent({ productType, data, metadata, language }) {
  if (productType === "legislative_dossier") return legislativeDossier({ data, language });
  if (productType === "product_document") return productDocument({ data, language });
  return generic({ data, language });
}