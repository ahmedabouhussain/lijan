export function templateFor(productType) {
  return TEMPLATE_REGISTRY[productType] || TEMPLATE_REGISTRY.raw_data_csv;
}

// Build the canonical document metadata block that travels with every file (cover + footer +
// audit). The caller never authors this — the engine does.
export function buildDocumentMetadata({
  productType, organizationName, committeeName, language, classification,
  requestedBy, purpose, itemCount, ameenDraft, referenceNumber, version,
}) {
  const tpl = templateFor(productType);
  const now = new Date();
  const isAr = language === "ar";
  const cls = CLASSIFICATION_LABELS[classification || "internal"] || CLASSIFICATION_LABELS.internal;
  return {
    product_type: productType,
    template_key: tpl.key,
    template_label: isAr ? tpl.ar : tpl.en,
    organization_name: organizationName || null,
    committee_name: committeeName || null,
    language,
    direction: isAr ? "rtl" : "ltr",
    classification: classification || "internal",
    classification_label: cls,
    reference_number: referenceNumber || null,
    version: version || "1.0",
    requested_by: requestedBy || null,
    purpose: purpose || null,
    item_count: itemCount ?? null,
    ameen_draft: !!ameenDraft,
    generated_at: now.toISOString(),
    generated_at_display: now.toLocaleString(isAr ? "ar-EG" : "en-GB"),
    lijan_logo_url: BRAND_LOGO_URL,
    connection_logo_url: CONNECTION_LOGO_URL,
    identity_text: isAr ? IDENTITY_TEXT.generatedByAr : IDENTITY_TEXT.generatedByEn,
    lockup_text: isAr ? IDENTITY_TEXT.lockupAr : IDENTITY_TEXT.lockupEn,
    ameen_draft_text: isAr ? IDENTITY_TEXT.ameenDraftAr : IDENTITY_TEXT.ameenDraftEn,
    engine_version: "institutional-export-1.0.0",
  };
}